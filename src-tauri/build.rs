//! Build script: reads `.env` (next to this file) and re-exports the
//! AuthForge and Stripe values as `cargo:rustc-env=...` so the Rust
//! source can `env!()` them at compile time.
//!
//! Behavior:
//!   * In `cargo build` (debug) missing values fall back to empty
//!     strings so the project compiles even with no `.env` present.
//!   * In `cargo build --release` (or `cargo tauri build`) any missing
//!     `AUTHFORGE_*` value causes the build to fail loudly.
//!
//! `.env` itself MUST be `.gitignore`d. Use `.env.example` at the repo
//! root as a template.

use std::env;
use std::fs;
use std::path::Path;
use std::path::PathBuf;

const REQUIRED_RELEASE_VARS: &[&str] = &[
    "AUTHFORGE_APP_ID",
    "AUTHFORGE_APP_SECRET",
    "AUTHFORGE_PUBLIC_KEY",
    "STRIPE_MONTHLY_URL",
    "STRIPE_LIFETIME_URL",
];

const ALL_VARS: &[&str] = &[
    "AUTHFORGE_APP_ID",
    "AUTHFORGE_APP_SECRET",
    "AUTHFORGE_PUBLIC_KEY",
    "STRIPE_MONTHLY_URL",
    "STRIPE_LIFETIME_URL",
];

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());

    let env_candidates = [
        manifest_dir.join(".env"),
        manifest_dir.parent().unwrap_or(&manifest_dir).join(".env"),
    ];

    let mut loaded_from: Option<PathBuf> = None;
    for candidate in &env_candidates {
        if candidate.is_file() {
            load_env_file(candidate);
            loaded_from = Some(candidate.clone());
            println!("cargo:rerun-if-changed={}", candidate.display());
            break;
        }
    }

    let profile = env::var("PROFILE").unwrap_or_else(|_| "debug".into());
    let is_release = profile == "release";

    let mut missing: Vec<&str> = Vec::new();
    for var in ALL_VARS {
        let val = env::var(var).unwrap_or_default();
        if val.is_empty() && is_release && REQUIRED_RELEASE_VARS.contains(var) {
            missing.push(var);
        }
        println!("cargo:rustc-env={}={}", var, val);
    }

    if !missing.is_empty() {
        let where_from = loaded_from
            .as_ref()
            .map(|p| p.display().to_string())
            .unwrap_or_else(|| "no .env file found".into());
        panic!(
            "release build is missing required env vars: {:?} (env source: {}). \
             Populate src-tauri/.env (see .env.example) or pass them as \
             environment variables in CI before running `cargo tauri build`.",
            missing, where_from
        );
    }

    for var in ALL_VARS {
        println!("cargo:rerun-if-env-changed={}", var);
    }

    write_secrets_module();

    // Windows: `tauri_build` embeds VERSION + icons via `tauri-winres` (bundle icon.ico). Do not
    // invoke a second `winres`/resource compile here — MSVC reports CVT1100 duplicate VERSION.
    tauri_build::build();

    #[cfg(windows)]
    {
        let ico = manifest_dir.join("icons").join("icon.ico");
        if !ico.is_file() {
            println!(
                "cargo:warning=icons/icon.ico missing — Windows resource embed will fail until you run: npm run icons:generate -- <your-square-png>"
            );
        } else {
            println!("cargo:rerun-if-changed={}", ico.display());
        }
    }
}

/// `cryptify::encrypt_string!` is a proc-macro that only accepts a
/// string literal token — not `env!()` expansions. To still obfuscate
/// env-injected values we generate a small Rust source file at build
/// time with the literals inlined inside the cryptify macro and have
/// `auth.rs` include it.
fn write_secrets_module() {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR not set");
    let dest = Path::new(&out_dir).join("secrets.rs");

    let app_id = env::var("AUTHFORGE_APP_ID").unwrap_or_default();
    let app_secret = env::var("AUTHFORGE_APP_SECRET").unwrap_or_default();
    let public_key = env::var("AUTHFORGE_PUBLIC_KEY").unwrap_or_default();
    let stripe_monthly = env::var("STRIPE_MONTHLY_URL").unwrap_or_default();
    let stripe_lifetime = env::var("STRIPE_LIFETIME_URL").unwrap_or_default();

    let body = format!(
        r#"// AUTO-GENERATED by build.rs. Do not edit.
//
// Values are baked at compile time and wrapped in
// `cryptify::encrypt_string!` so they never appear contiguously in
// the binary's `.rdata` / `.rodata` section.

#[inline(always)]
pub(crate) fn authforge_app_id() -> String {{
    cryptify::encrypt_string!({app_id}).to_string()
}}

#[inline(always)]
pub(crate) fn authforge_app_secret() -> String {{
    cryptify::encrypt_string!({app_secret}).to_string()
}}

#[inline(always)]
pub(crate) fn authforge_public_key() -> String {{
    cryptify::encrypt_string!({public_key}).to_string()
}}

#[inline(always)]
pub(crate) fn stripe_monthly_url() -> String {{
    cryptify::encrypt_string!({stripe_monthly}).to_string()
}}

#[inline(always)]
pub(crate) fn stripe_lifetime_url() -> String {{
    cryptify::encrypt_string!({stripe_lifetime}).to_string()
}}
"#,
        app_id = quote_literal(&app_id),
        app_secret = quote_literal(&app_secret),
        public_key = quote_literal(&public_key),
        stripe_monthly = quote_literal(&stripe_monthly),
        stripe_lifetime = quote_literal(&stripe_lifetime),
    );

    fs::write(&dest, body).expect("could not write secrets.rs");
}

/// Render a Rust string literal token containing `s`, escaping
/// backslashes and double-quotes.
fn quote_literal(s: &str) -> String {
    let escaped = s.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{}\"", escaped)
}

fn load_env_file(path: &PathBuf) {
    let Ok(contents) = fs::read_to_string(path) else {
        return;
    };
    for raw in contents.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let key = key.trim();
        let value = strip_surrounding_quotes(value.trim());
        if env::var_os(key).is_none() {
            env::set_var(key, value);
        }
    }
}

fn strip_surrounding_quotes(s: &str) -> &str {
    if (s.starts_with('"') && s.ends_with('"') && s.len() >= 2)
        || (s.starts_with('\'') && s.ends_with('\'') && s.len() >= 2)
    {
        &s[1..s.len() - 1]
    } else {
        s
    }
}
